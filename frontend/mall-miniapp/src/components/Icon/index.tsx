export type IconName = keyof typeof ICON_PATHS

interface IconProps {
  /** 图标名 */
  name: IconName
  /** 尺寸（rpx），默认 40 */
  size?: number
  /** 描边颜色，默认主文本色 */
  color?: string
  /** 描边宽度，默认 2 */
  strokeWidth?: number
  className?: string
}

function Icon({ name, size = 40, color = '#1d2129', strokeWidth = 2, className }: IconProps) {
  const src = useMemo(() => {
    const body = ICON_PATHS[name] || ICON_PATHS['shopping-bag']
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`
    return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`
  }, [name, color, strokeWidth])

  // H5 不会转换 JS 内联样式里的 rpx（只处理 .scss），尺寸会失效导致图标被撑成默认大小，
  // 因此 H5 用等价的 vw 换算（size rpx === size/750*100 vw），两端尺寸一致且随屏幕自适应
  const iconSize = useMemo(
    () => (process.env.TARO_ENV === 'h5' ? `${((size / 750) * 100).toFixed(4)}vw` : `${size}rpx`),
    [size],
  )

  return <Image className={className} src={src} style={{ width: iconSize, height: iconSize }} />
}

export default Icon
